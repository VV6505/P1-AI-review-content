const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
const output = path.resolve('test-results/p1-requirements');

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : { channel: 'chrome' }) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/login');
    await page.getByLabel('Tài khoản', { exact: true }).fill('creator');
    await page.getByLabel('Mật khẩu', { exact: true }).fill('123456');
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await page.waitForURL('**/creator/create');
    await page.getByRole('button', { name: 'Thử với AISoEasy', exact: true }).click();
    const description = page.getByLabel('Mô tả / mong muốn về video', { exact: true });
    assert.equal(await page.getByLabel('Link sản phẩm (bắt buộc)', { exact: true }).inputValue(), 'https://aisoeasy.com');
    assert.match(await description.inputValue(), /nhân viên văn phòng/);
    await description.fill('Giới thiệu việc học AI cho nhân viên văn phòng, giọng thân thiện.');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#video-description')?.value.includes('nhân viên văn phòng'));
    assert.match(await description.inputValue(), /nhân viên văn phòng/);
    await page.screenshot({ path: path.join(output, 'creator-description-desktop.png'), fullPage: true });
    await page.getByRole('button', { name: 'Tạo video', exact: true }).click();
    await page.getByLabel('Tên sản phẩm', { exact: true }).waitFor();
    await page.getByLabel('Tên sản phẩm', { exact: true }).fill('AISoEasy');
    await page.getByLabel('Mô tả sản phẩm', { exact: true }).fill('Thông tin kiểm thử bước xác nhận, không phải dữ liệu AI thật.');
    await page.getByRole('button', { name: 'Xác nhận sản phẩm', exact: true }).click();
    await page.getByRole('button', { name: 'Xong', exact: true }).click();
    const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('reviewlab.studio.v1')));
    const before = await state(), balance = before.users.find(user => user.id === 'demo').tokens;
    await page.getByRole('button', { name: 'Tạo video', exact: true }).click();
    const review = page.getByRole('dialog', { name: 'Duyệt yêu cầu video', exact: true });
    await review.waitFor();
    assert.equal((await state()).requests.length, 0);
    assert.equal((await state()).users.find(user => user.id === 'demo').tokens, balance);
    const edited = 'Hướng dẫn nhân viên văn phòng; <script>window.injected=true</script> là dữ liệu chữ.';
    await review.getByLabel('Mô tả / mong muốn về video', { exact: true }).fill(edited);
    await review.getByRole('button', { name: 'Đóng', exact: true }).click();
    await page.reload();
    await page.waitForFunction(value => document.querySelector('#video-description')?.value === value, edited);
    assert.equal(await description.inputValue(), edited);
    assert.equal((await state()).draft.requirementsReview, null);
    await page.getByRole('button', { name: 'Tạo video', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'requirements-review-desktop.png'), fullPage: true });
    await review.getByRole('button', { name: 'Xác nhận và xem mẫu', exact: true }).dblclick();
    await page.waitForURL('**/creator/project/*');
    const saved = await state(), request = saved.requests[0];
    assert.equal(saved.requests.length, 1);
    assert.equal(request.notes, edited);
    assert.equal(request.requirementsReview.version, 1);
    assert.equal(JSON.parse(request.requirementsReview.snapshot).notes, edited);
    assert.equal(saved.users.find(user => user.id === 'demo').tokens, balance - request.estimatedTokens);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    await page.getByText('Xem yêu cầu & cấu hình', { exact: true }).click();
    assert.ok(await page.getByText('Yêu cầu đã xác nhận cho lần xem mẫu này.', { exact: true }).isVisible());
    await description.fill('Đổi sang nội dung cho người mới bắt đầu.');
    assert.equal((await state()).draft.requirementsReview, null);
    assert.equal((await state()).requests[0].notes, edited, 'history is immutable');
    await page.getByRole('button', { name: 'Tạo video', exact: true }).click();
    assert.equal(await review.getByLabel('Mô tả / mong muốn về video', { exact: true }).inputValue(), 'Đổi sang nội dung cho người mới bắt đầu.');
    await review.getByRole('button', { name: 'Đóng', exact: true }).click();
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `composer fits ${width}px`);
      await page.getByRole('button', { name: 'Tạo video', exact: true }).click();
      await review.waitFor();
      assert.ok(await review.evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), `review fits ${width}px`);
      await page.screenshot({ path: path.join(output, `requirements-review-${width}.png`), fullPage: true });
      await review.getByRole('button', { name: 'Đóng', exact: true }).click();
    }
    await page.evaluate(() => { localStorage.setItem('reviewlab.theme', 'dark'); localStorage.setItem('reviewlab.language', 'en'); });
    await page.reload();
    await page.waitForFunction(() => document.documentElement.lang === 'en' && document.documentElement.classList.contains('dark') && document.querySelector('.chat-composer fieldset')?.disabled === false);
    await page.getByRole('button', { name: 'Create video', exact: true }).click();
    const englishReview = page.getByRole('dialog', { name: 'Review video requirements', exact: true });
    await englishReview.getByRole('button', { name: 'Confirm and view sample', exact: true }).scrollIntoViewIfNeeded();
    assert.ok(await englishReview.getByRole('button', { name: 'Confirm and view sample', exact: true }).isVisible());
    assert.ok(await englishReview.evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth));
    await page.screenshot({ path: path.join(output, 'requirements-review-dark-en-320.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS: AISoEasy description, product confirmation, requirements review/cancel/reload, exact approval, single debit, immutable history, text escaping and mobile 390/320.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
